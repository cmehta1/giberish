// Write supabase/seed.sql from the catalogue in assets/js/data.js (products + notes) and the art map in art.js.
//   node tools/export-seed.mjs
// Run the file in Supabase → SQL Editor. It inserts or updates, so it is safe to run again,
// but it overwrites edits made in the admin panel for the same products/notes.
import fs from 'node:fs';

const win = {};
new Function('window', fs.readFileSync('assets/js/data.js', 'utf8'))(win);
const art = fs.readFileSync('assets/js/art.js', 'utf8');
const MAP = new Function(`return ${/const MAP = (\{[\s\S]*?\n  \});/.exec(art)[1]}`)();

// where each note naturally sits in a perfume (also used by Scent Alchemy and the Journey)
const TIER = {
  citrus: 'top', cardamom: 'top', saffron: 'top', green: 'top', apple: 'top', peach: 'top', raspberry: 'top', blackcurrant: 'top', bergamot: 'top',
  rose: 'heart', jasmine: 'heart', leather: 'heart', peony: 'heart', orangeblossom: 'heart', orchid: 'heart', candy: 'heart', marshmallow: 'heart', caramel: 'heart', coffee: 'heart',
  oud: 'base', sandalwood: 'base', cedar: 'base', amber: 'base', vanilla: 'base', musk: 'base', smoke: 'base', tonka: 'base', cocoa: 'base', praline: 'base', cashmere: 'base', vetiver: 'base',
};

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (o) => (o == null ? 'null' : `${q(JSON.stringify(o))}::jsonb`);

const notes = Object.entries(win.GIB_INGREDIENTS).map(([key, n], i) =>
  `(${[q(key), q(n.label), json(n.family), q(n.color || null), MAP[key] ? arr(MAP[key]) : 'null', q(TIER[key] || null), (i + 1) * 10].join(', ')})`);

const products = win.GIB_PRODUCTS.map((p, i) =>
  `(${[q(p.id), q(p.name), q(p.house), q(p.type), q(p.size), p.price == null ? 'null' : p.price, q(p.image), q(p.tagline), q(p.story),
    json(p.notes), arr(p.ingredients), arr(p.feel), p.featured ? 'true' : 'false', q(p.world || null), q(p.sound || null), json(p.nozzle || null), (i + 1) * 10].join(', ')})`);

const sql = `-- Giberish catalogue, generated by tools/export-seed.mjs from assets/js/data.js
-- Run after schema.sql. Re-running overwrites admin-panel edits for these rows.

insert into public.notes (key, label, family, color, art, tier, sort) values
${notes.join(',\n')}
on conflict (key) do update set label = excluded.label, family = excluded.family, color = excluded.color,
  art = excluded.art, tier = excluded.tier, sort = excluded.sort, active = true;

insert into public.products (id, name, house, type, size, price, image, tagline, story, notes, ingredients, feel, featured, world, sound, nozzle, sort) values
${products.join(',\n')}
on conflict (id) do update set name = excluded.name, house = excluded.house, type = excluded.type, size = excluded.size,
  price = excluded.price, image = excluded.image, tagline = excluded.tagline, story = excluded.story, notes = excluded.notes,
  ingredients = excluded.ingredients, feel = excluded.feel, featured = excluded.featured, world = excluded.world,
  sound = excluded.sound, nozzle = excluded.nozzle, sort = excluded.sort, active = true;
`;
fs.mkdirSync('supabase', { recursive: true });
fs.writeFileSync('supabase/seed.sql', sql);
console.log(`supabase/seed.sql: ${notes.length} notes, ${products.length} products`);
